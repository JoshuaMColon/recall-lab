"""Build src/data/d335.json: course, objectives and the verified question bank.

Run: python3 scripts/bank/build.py   (CPython 3.11+; every answer is computed by running code)
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import lib, o01_03, o04_07, o08_11  # noqa: E401,F401  (modules register questions on import)

COURSE = {
    "code": "D335",
    "title": "Introduction to Programming in Python",
    "summary": "Writing small Python scripts: data, control flow, functions, collections, errors, modules and files.",
    "note": "Objective wording is Recall Lab's own paraphrase of the publicly described course competencies; it is not official WGU or zyBooks material.",
    "competencies": [
        {"id": "A", "title": "Scripts with control flow", "summary": "Write Python programs that store data, make decisions, repeat work, organise logic into functions and handle errors."},
        {"id": "B", "title": "Reuse and file I/O", "summary": "Pull in functionality from modules and the standard library, and read and write files."},
    ],
}
OBJECTIVES = [
    ("01", "A", "Variables, expressions & operators", "Assign and update variables; evaluate arithmetic with + - * / // % ** and precedence; use augmented assignment.", 8),
    ("02", "A", "Input, output & type conversion", "Read text with input(), convert with int(), float() and str(), and format output with print options and f-strings.", 10),
    ("03", "A", "Branching & Boolean logic", "Write if / elif / else chains; combine conditions with and, or, not; reason about comparisons and truthiness.", 10),
    ("04", "A", "Loops", "Repeat work with for over range() and sequences, and with while; use break, continue, accumulators and nested loops.", 12),
    ("05", "A", "Functions", "Define functions with parameters, defaults and return values; tell return from print; understand local vs global scope.", 12),
    ("06", "A", "Strings", "Index and slice strings, use common string methods, and remember that strings are immutable.", 10),
    ("07", "A", "Lists & tuples", "Create, index, slice and change lists; use list methods and comprehensions; know when to use an immutable tuple.", 10),
    ("08", "A", "Dictionaries & sets", "Store and look up key-value pairs, iterate with items(), use get() and membership tests, and de-duplicate with sets.", 8),
    ("09", "A", "Exceptions & debugging", "Read tracebacks, recognise common runtime errors, and handle them with try / except / else / finally and raise.", 6),
    ("10", "B", "Modules & libraries", "Import modules in different ways and use standard-library modules such as math, random, datetime and string; know what __name__ == '__main__' does.", 8),
    ("11", "B", "Files", "Open files in the right mode, read and write text, close files automatically with with, and process CSV-style rows.", 6),
]

def main():
    objectives = [dict(id=f"D335.{n}", code=n, competency=c, title=t, summary=s, weight=w, position=i + 1)
                  for i, (n, c, t, s, w) in enumerate(OBJECTIVES)]
    for q in lib.QUESTIONS:
        q["objective"] = f"D335.{q['objective']}"
    ids = [q["id"] for q in lib.QUESTIONS]
    assert len(ids) == len(set(ids)), "duplicate ids"
    data = dict(version=1, course=COURSE, objectives=objectives, questions=lib.QUESTIONS)
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    path = os.path.join(root, "src", "data", "d335.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write("\n")
    # The API functions only need the objective list; keep them free of the 140 KB bank.
    api = os.path.join(root, "api", "_objectives.ts")
    with open(api, "w") as f:
        f.write("// Generated by scripts/bank/build.py. Do not edit.\n")
        f.write("export const COURSE_TITLE = " + json.dumps(f"{COURSE['code']} {COURSE['title']}") + "\n")
        f.write("export const OBJECTIVES: Record<string, { title: string; summary: string }> = ")
        f.write(json.dumps({o["id"]: dict(title=o["title"], summary=o["summary"]) for o in objectives}, indent=2, ensure_ascii=False))
        f.write("\n")
    by = {}
    for q in lib.QUESTIONS:
        by.setdefault(q["objective"], {}).setdefault(q["type"], 0)
        by[q["objective"]][q["type"]] += 1
    print(f"wrote {len(lib.QUESTIONS)} questions to {os.path.relpath(path, root)}")
    for k in sorted(by):
        print(" ", k, by[k])

if __name__ == "__main__":
    main()
